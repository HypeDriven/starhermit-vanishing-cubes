// Precomputes the Journey stages and the challenge boards (fixed seeds) into
// js/content/generated.js: generateLevel runs ~20x slower in the engine's
// native interpreter (~8 s for the 40 stages), so the client reads this table.
// tests/content.test.mjs checks it still matches the generator.
//   node tools/gen-levels.mjs
import { writeFileSync } from 'node:fs';
import { generateLevel } from '../js/rules/generator.js';
import { LEVEL_DEFS } from '../js/content/levels.js';
import { CHALLENGES } from '../js/content/challenges.js';

export function buildTable() {
  const out = {};
  for (const d of LEVEL_DEFS) out[d.id] = generateLevel(d);
  for (const c of CHALLENGES) out['challenge:' + c.id] = generateLevel(c.def);
  return out;
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const json = JSON.stringify(buildTable());
  writeFileSync(new URL('../js/content/generated.js', import.meta.url),
    '// Generated by tools/gen-levels.mjs — the Journey stages and challenge boards (do not edit).\nexport const GENERATED = ' + json + ';\n');
  console.log('generated.js', json.length, 'bytes');
}
